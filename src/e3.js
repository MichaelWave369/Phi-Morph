/**
 * Φ-Morph E3: exploratory point-node versus flat-ground unilateral contact.
 * No tire tread, rotation, adhesion, calibrated units, membrane, or fluid model.
 * A vertically translating hub is connected to 24 nodes via actuated springs.
 * Link springs retain E1's fixed 48-edge topology. Only the ground reacts.
 */
import { CELL_COUNT, GEOMETRIES, DEFAULTS, clampParameters } from "./model.js";
import { normalizedLayout, regularEdges } from "./e1.js";

export const E3_PROTOCOL = "PM-E3-0.4.0";
export const E3_MODEL = "phi-morph-unilateral-contact-0.4.0";
export const E3_LOADS = Object.freeze([0.5, 1, 2, 4]);
export const E3_SURFACES = Object.freeze({
  soft: Object.freeze({ stiffness: 35, closingDamping: 2 }),
  firm: Object.freeze({ stiffness: 100, closingDamping: 3.5 }),
});
export const E3_RADIUS = 0.22;
export const E3_DT = 0.01;
export const E3_DURATION = 8;
export const E3_FRAME_STRIDE = 25;
const HUB_MASS = 2;
const NODE_MASS = 1;
const round = (n) => Math.round(n * 1e6) / 1e6;

export function e3GroundForce(y, vy, surface = "soft", enabled = true) {
  if (!Object.hasOwn(E3_SURFACES, surface)) throw new Error("Unknown contact surface");
  if (!Number.isFinite(y) || !Number.isFinite(vy)) throw new Error("Invalid contact state");
  if (!enabled) return 0;
  const penetration = E3_RADIUS - y;
  if (penetration <= 0) return 0;
  const material = E3_SURFACES[surface];
  // Compression-only penalty + closing-speed damping, clamped nonadhesive.
  return Math.max(0, material.stiffness * penetration +
    material.closingDamping * Math.max(0, -vy));
}

function snapshot(step, hub, nodes) {
  return {
    step,
    time: round(step * E3_DT),
    hubY: round(hub.y),
    nodes: nodes.map((node) => ({
      id: node.id,
      x: round(node.x),
      y: round(node.y),
      touching: node.y <= E3_RADIUS,
    })),
  };
}

export function simulateE3(
  geometry = "ring",
  rawParameters = DEFAULTS,
  { surface = "soft", contactEnabled = true, saveFrames = false, dt = E3_DT, duration = E3_DURATION } = {}
) {
  if (!Object.hasOwn(E3_SURFACES, surface)) throw new Error("Unknown contact surface");
  if (typeof contactEnabled !== "boolean") throw new Error("Invalid contact flag");
  if (!(Number.isFinite(dt) && dt > 0 && dt <= 0.02)) throw new Error("Invalid timestep");
  if (!(Number.isFinite(duration) && duration > 0 && duration <= 12)) throw new Error("Invalid duration");
  const steps = Math.round(duration / dt);
  if (Math.abs(steps * dt - duration) > 1e-9) throw new Error("Duration must be a multiple of dt");
  const p = clampParameters(rawParameters);
  const reference = normalizedLayout(geometry);
  const edges = regularEdges(reference);
  // Start with clearance above the surface so first contact is generated by
  // dynamics, not by a pre-imposed support reaction.
  const minRefY = Math.min(...reference.map((point) => point.y));
  const hub = { y: E3_RADIUS + 0.04 - minRefY, vy: 0 };
  const initialHubY = hub.y;
  const nodes = reference.map((node) => ({
    id: node.id, x: node.x, y: node.y + hub.y, vx: 0, vy: 0,
  }));
  const frames = saveFrames ? [snapshot(0, hub, nodes)] : [];
  let maxPenetration = 0;
  let maxSpokeExtension = 0;
  let peakNormalReaction = 0;
  let totalLateNormal = 0;
  let totalLateHubVelocity = 0;
  let lateSamples = 0;
  let finite = true;
  const lastQuarterStart = Math.floor(steps * 0.75);
  const spokeK = 3.5 * p.stiffness;
  const linkK = 1.5 * p.stiffness;

  for (let step = 0; step < steps; step++) {
    const time = step * dt;
    const fx = new Float64Array(CELL_COUNT);
    const fy = new Float64Array(CELL_COUNT);
    let hubFy = -p.load;
    let normalTotal = 0;

    for (let i = 0; i < CELL_COUNT; i++) {
      const ref = reference[i];
      const n = nodes[i];
      const breathing = p.frequency === 0 ? 0 :
        0.015 * p.pressure * Math.sin(2 * Math.PI * p.frequency * time);
      const scale = 1 + 0.035 * p.pressure + breathing;
      const targetX = ref.x * scale;
      const targetY = ref.y * scale;
      const relativeX = n.x;
      const relativeY = n.y - hub.y;
      const spokeFx = spokeK * (targetX - relativeX);
      const spokeFy = spokeK * (targetY - relativeY);
      fx[i] += spokeFx;
      fy[i] += spokeFy;
      hubFy -= spokeFy; // exactly opposite force, no invisible absolute tether
      maxSpokeExtension = Math.max(maxSpokeExtension,
        Math.hypot(targetX - relativeX, targetY - relativeY));

      const normal = e3GroundForce(n.y, n.vy, surface, contactEnabled);
      fy[i] += normal;
      normalTotal += normal;
      maxPenetration = Math.max(maxPenetration, contactEnabled ?
        Math.max(0, E3_RADIUS - n.y) : 0);
    }

    for (const edge of edges) {
      const a = nodes[edge.a], b = nodes[edge.b];
      const dx = b.x - a.x, dy = b.y - a.y;
      const distance = Math.max(1e-12, Math.hypot(dx, dy));
      const extension = distance - edge.rest;
      const magnitude = linkK * extension / distance;
      fx[edge.a] += magnitude * dx;
      fy[edge.a] += magnitude * dy;
      fx[edge.b] -= magnitude * dx;
      fy[edge.b] -= magnitude * dy;
    }

    peakNormalReaction = Math.max(peakNormalReaction, normalTotal);
    if (step >= lastQuarterStart) {
      totalLateNormal += normalTotal;
      totalLateHubVelocity += Math.abs(hub.vy);
      lateSamples++;
    }

    // The hub is horizontally constrained to isolate vertical compression.
    // Only vertical external force, spoke reactions and damping act on it.
    hub.vy = (hub.vy + hubFy / HUB_MASS * dt) / (1 + p.damping * 0.42 * dt);
    hub.y += hub.vy * dt;
    for (const node of nodes) {
      node.vx = (node.vx + fx[node.id] / NODE_MASS * dt) /
        (1 + p.damping * 0.38 * dt);
      node.vy = (node.vy + fy[node.id] / NODE_MASS * dt) /
        (1 + p.damping * 0.38 * dt);
      node.x += node.vx * dt;
      node.y += node.vy * dt;
    }

    if (![hub.y, hub.vy, ...nodes.flatMap((n) => [n.x, n.y, n.vx, n.vy])].every(Number.isFinite)) {
      finite = false;
      break;
    }
    if (saveFrames && ((step + 1) % E3_FRAME_STRIDE === 0 || step === steps - 1)) {
      frames.push(snapshot(step + 1, hub, nodes));
    }
  }

  if (!finite) return {
    geometry, surface, contactEnabled, parameters: p, numericallyFinite: false,
    initialHubY: round(initialHubY), edgeCount: edges.length, metrics: null,
    frames: saveFrames ? frames : undefined,
  };

  const touching = contactEnabled ? nodes.filter((n) => n.y <= E3_RADIUS) : [];
  const span = touching.length >= 2 ?
    Math.max(...touching.map((n) => n.x)) - Math.min(...touching.map((n) => n.x)) : 0;
  const finalNormal = nodes.reduce((sum, n) =>
    sum + e3GroundForce(n.y, n.vy, surface, contactEnabled), 0);
  return {
    geometry, surface, contactEnabled, parameters: p, numericallyFinite: true,
    initialHubY: round(initialHubY), edgeCount: edges.length,
    dt, steps, duration,
    metrics: {
      hubDrop: round(initialHubY - hub.y),
      finalHubY: round(hub.y),
      finalContactNodes: touching.length,
      finalContactSpanProxy: round(span),
      finalNormalReaction: round(finalNormal),
      peakNormalReaction: round(peakNormalReaction),
      peakPenetration: round(maxPenetration),
      maxSpokeExtension: round(maxSpokeExtension),
      lateMeanNormalReaction: round(totalLateNormal / Math.max(1, lateSamples)),
      lateMeanAbsHubVelocity: round(totalLateHubVelocity / Math.max(1, lateSamples)),
      lateNormalToLoadRatio: p.load > 0 ?
        round(totalLateNormal / Math.max(1, lateSamples) / p.load) : null,
    },
    // Preview only: batch receipts intentionally keep 24-case results compact.
    frames: saveFrames ? frames : undefined,
    finalNodes: saveFrames ? nodes.map((n) => ({
      id: n.id, x: round(n.x), y: round(n.y),
    })) : undefined,
  };
}

export function buildE3Receipt(rawParameters = DEFAULTS, recordedAt = new Date().toISOString()) {
  const p = clampParameters(rawParameters);
  const cases = GEOMETRIES.flatMap(({ id: geometry }) =>
    Object.keys(E3_SURFACES).flatMap((surface) =>
      E3_LOADS.map((load) => {
        const result = simulateE3(geometry, { ...p, load }, { surface });
        return {
          geometry, surface, load, numericallyFinite: result.numericallyFinite,
          metrics: result.metrics,
        };
      })));
  const controls = GEOMETRIES.map(({ id: geometry }) => {
    const result = simulateE3(geometry, { ...p, load: 2 }, {
      surface: "soft", contactEnabled: false,
    });
    return { geometry, load: 2, contactEnabled: false,
      normalReaction: result.metrics?.lateMeanNormalReaction ?? null,
      numericallyFinite: result.numericallyFinite,
      hubDrop: result.metrics?.hubDrop ?? null };
  });
  return {
    schema: "phi-morph.e3.receipt.v1",
    origin: "SIMULATED",
    physicalValidation: "NONE",
    modelVersion: E3_MODEL,
    protocol: E3_PROTOCOL,
    recordedAt,
    units: "normalized_dimensionless",
    parameters: p,
    controls: {
      nodeCount: CELL_COUNT,
      edgeCount: 48,
      verticalHubMotionOnly: true,
      contactLaw: "unilateral_penalty_plus_closing_damping_no_adhesion",
      floorHeight: 0,
      nodeRadius: E3_RADIUS,
      dt: E3_DT,
      duration: E3_DURATION,
      surfaceParameters: E3_SURFACES,
      loads: [...E3_LOADS],
      caseCount: cases.length,
      negativeControlCount: controls.length,
    },
    cases,
    noContactControls: controls,
    limitations: [
      "Normalized point-node contact proxy, not a tire, footprint area, friction or traction model.",
      "No rolling, vehicle mass, physical pressure, finite element continuum, membranes or water.",
      "The hub is constrained horizontally; spoke springs can support load only through ground-contacting nodes.",
      "Penalty-spring penetration is numerical overlap, not physical material deformation.",
      "Late-window averaged reaction need not equal applied load: the system may not reach equilibrium.",
      "Different shapes still differ in link lengths, orientation, and spatial envelopes.",
    ],
  };
}

export function e3Csv(receipt) {
  const rows = [[
    "protocol","geometry","surface","load","hubDrop","peakPenetration",
    "lateMeanNormalReaction","lateNormalToLoadRatio","finalContactNodes",
    "finalContactSpanProxy","numericallyFinite",
  ]];
  for (const row of receipt.cases) {
    rows.push([
      receipt.protocol, row.geometry, row.surface, row.load,
      row.metrics?.hubDrop ?? "", row.metrics?.peakPenetration ?? "",
      row.metrics?.lateMeanNormalReaction ?? "",
      row.metrics?.lateNormalToLoadRatio ?? "",
      row.metrics?.finalContactNodes ?? "",
      row.metrics?.finalContactSpanProxy ?? "", row.numericallyFinite,
    ]);
  }
  return rows.map((r) => r.map((v) =>
    '"' + String(v).replace(/"/g, '""') + '"').join(",")).join("\n") + "\n";
}
